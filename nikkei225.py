def _valid(code: str) -> bool:
    return bool(re.fullmatch(r"\d[0-9A-Z]{3}", code))


def _dedupe(codes) -> list[str]:
    out, seen = [], set()
    for c in codes:
        c = c.strip().upper()
        if c and c not in seen and _valid(c):
            seen.add(c)
            out.append(c)
    return out


def load_universe(path: str = UNIVERSE_PATH) -> list[str]:
    """スキャン対象の銘柄コード。state/universe.txt があればそれを使う。"""
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            codes = _dedupe(line.split("#")[0] for line in f)
        if codes:
            print(f"[universe] {path} の {len(codes)} 銘柄を対象にする")
            return codes
        print(f"[universe] {path} が空なので日経225を使う")
    return _dedupe(NIKKEI225)
