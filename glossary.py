# 目印の重複チェック用（テストで使う）
TERM_NAMES = [t[0] for t in TERMS]


def terms_in(texts) -> list[str]:
    """通知本文に出てきた用語（TERMS の並び順）。texts は文字列か文字列のリスト。"""
    if isinstance(texts, str):
        texts = [texts]
    blob = "\n".join(texts)
    return [name for name, marks, _ in TERMS if any(m in blob for m in marks)]


def record(state: dict, texts, day: date) -> list[str]:
    """その日の通知に出た用語を state に足す（実行をまたいで1日ぶん貯める）。"""
    found = terms_in(texts)
    if not found:
        return []
    key = f"glossary:{day.isoformat()}"
    e = state.get(key)
    if e is None or e.get("sent"):
        # 送信済みの日にさらに通知が出た（手動で早めに流した等）→ 次の用語解説で送り直す
        e = state[key] = {"d": day.isoformat(), "s": "glossary", "t": []}
    for t in found:
        if t not in e["t"]:
            e["t"].append(t)
    return found


def pending(state: dict) -> list[str]:
    """まだ送っていない日のキー（古い順）。"""
    return sorted(k for k, v in state.items()
                  if k.startswith("glossary:") and v.get("s") == "glossary" and not v.get("sent"))


def fallback_terms(day: date, n: int | None = None) -> list[str]:
    """通知が無かった日に解説する基本用語（日替わり）。"""
    n = config.GLOSSARY_FALLBACK if n is None else n
    start = (day.toordinal() * n) % len(TERMS)
    return [TERMS[(start + i) % len(TERMS)][0] for i in range(min(n, len(TERMS)))]


def fmt_glossary(names: list[str], now: datetime, fallback: bool = False) -> str:
    """用語解説の本文。names は TERMS の用語名。"""
    expl = {name: text for name, _, text in TERMS}
    order = [n for n in TERM_NAMES if n in names]
    head = f"【今日の用語解説】{now:%m/%d}"
    if fallback:
        lead = "今日は通知がなかったので、基本の用語を紹介します。"
    else:
        lead = f"今日の通知に出てきた言葉 {len(order)}個を、かんたんに解説します。"
    lines = [head, lead, ""]
    for n in order:
        lines.append(f"■ {n}")
        lines.append(f" {expl[n]}")
    lines += ["", "※意味が分かると、通知の数字が「買う理由」「買わない理由」として読めるようになります"]
    return "\n".join(lines)


def build(state: dict, now: datetime, allow_fallback: bool = True) -> str:
    """送る本文を作り、該当日に送信済みの印を付ける。送るものが無ければ ""。"""
    keys = pending(state)
    names: list[str] = []
    for k in keys:
        for t in state[k].get("t", []):
            if t not in names:
                names.append(t)
    if names:
        for k in keys:
            state[k]["sent"] = True
        return fmt_glossary(names, now)
    if not allow_fallback:
        return ""
    day = now.date()
    key = f"glossary:{day.isoformat()}"
    if state.get(key, {}).get("sent"):
        return ""          # 今日はもう送った（手動で2回流したときの二重送信を防ぐ）
    state[key] = {"d": day.isoformat(), "s": "glossary", "t": [], "sent": True}
    return fmt_glossary(fallback_terms(day), now, fallback=True)
